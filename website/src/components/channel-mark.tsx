function Marks({ name, tone }: { name: ChannelName; tone: "mono" | "color" }) {
  const gradient = `tg-${useId().replace(/:/g, "")}`;
  const color = tone === "color";
  switch (name) {
    case "telegram":
      return color ? (
        <>
          <defs>
            <linearGradient id={gradient} x1="0.5" y1="0" x2="0.5" y2="1">
              <stop offset="0" stopColor="#2AABEE" />
              <stop offset="1" stopColor="#229ED9" />
            </linearGradient>
          </defs>
          <circle cx="12" cy="12" r="12" fill={`url(#${gradient})`} />
          <path fill="#fff" d={TELEGRAM_PLANE} />
        </>
      ) : (
        // The plane is cut out of the disc, as Simple Icons draws it.
        <path fill="currentColor" d={`${TELEGRAM_DISC}${TELEGRAM_PLANE.replace(/^M16\.906 7\.224/, "m4.962 7.224")}`} />
      );
    case "discord":
      return <path fill={color ? "#5865F2" : "currentColor"} d={DISCORD} />;
    case "slack":
      return (
        <>
          {SLACK.map((part) => (
            <path key={part.fill} fill={color ? part.fill : "currentColor"} d={part.d} />
          ))}
        </>
      );
    case "matrix":
      return <path fill="currentColor" d={MATRIX} />;
  }
}

export function ChannelMark({
  name,
  tone = "mono",
  size = 20,
  className,
}: {
  name: ChannelName;
  tone?: "mono" | "color";
  size?: number;
  className?: string;
}) {
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} className={className} aria-hidden="true" focusable="false">
      <Marks name={name} tone={tone} />
    </svg>
  );
}
